    public static Date getTanggalFromTable (JTable table, int kolom){
        JTable tabele = table;
        String tgl= String.valueOf(table.getValueAt(table.getSelectedRow(),kolom));
        Date tanggal = null;
        try{
            tanggal = new SimpleDateFormat("yyyy-MM-dd").parse(tgl);
            
        }catch(ParseException ex){
            Logger.getLogger(client.class.getName()).log(Level.SEVERE,null,ex);
        }
        return tanggal;
    }
    
    private void noklien() {
       try {
            String sql="select * from tb_konsumen order by dbkodeksm desc";
            stm=conn.createStatement();
            res=stm.executeQuery(sql);
            if (res.next()) {
                String nofak = res.getString("dbkodeksm").substring(1);
                String AN = "" + (Integer.parseInt(nofak) + 1);
                String Nol = "";

                if(AN.length()==1)
                {Nol = "000";}
                else if(AN.length()==2)
                {Nol = "00";}
                else if(AN.length()==3)
                {Nol = "0";}
                else if(AN.length()==4)
                {Nol = "";}

               kode.setText("K" + Nol + AN);
            } else {
               kode.setText("K0001");
            }

           }catch(Exception e){
           }
     }
    
