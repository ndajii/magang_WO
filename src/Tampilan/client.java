    private void TableClientMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_TableClientMouseClicked
        // TODO add your handling code here:
        int bar = TableClient.getSelectedRow();
        tglreservasi.setDate(getTanggalFromTable(TableClient, 0));
        String a = TableClient.getValueAt(bar, 1).toString();
        String b = TableClient.getValueAt(bar, 2).toString();
        String c = TableClient.getValueAt(bar, 3).toString();
        String d = TableClient.getValueAt(bar, 4).toString();
        String e = TableClient.getValueAt(bar, 5).toString();
        String f = TableClient.getValueAt(bar, 6).toString();
        
        kode.setText(a);
        nama.setText(b);
        if("Laki-Laki".equals(c)){
            laki.setSelected(true);
        }else {
            perempuan.setSelected(true);
        }
        agama.setSelectedItem(d);
        alamat.setText(e);
        telp.setText(f);
    }//GEN-LAST:event_TableClientMouseClicked

