    private void nokaryawan()
    {
       try {
            String sql="select * from tb_karyawan order by dbkodekar desc";
            stm=conn.createStatement();
            res=stm.executeQuery(sql);
            if (res.next()) {
                String nofak = res.getString("dbkodekar").substring(1);
                String AN = "" + (Integer.parseInt(nofak) + 1);
                String Nol = "";

                if(AN.length()==1)
                {Nol = "000";}
                else if(AN.length()==2)
                {Nol = "00";}
                else if(AN.length()==3)
                {Nol = "0";}
                else if(AN.length()==4)
                {Nol = "";}

               kode.setText("F" + Nol + AN);
            } else {
               kode.setText("F0001");
            }

           }catch(Exception e){
           JOptionPane.showMessageDialog(null, e);
           }
     }
    
