    private void tablestaffMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tablestaffMouseClicked
        // TODO add your handling code here:
        int bar = tablestaff.getSelectedRow();
        String a = tablestaff.getValueAt(bar, 0).toString();
        String b = tablestaff.getValueAt(bar, 1).toString();
        String c = tablestaff.getValueAt(bar, 2).toString();
        String d = tablestaff.getValueAt(bar, 3).toString();
        String e = tablestaff.getValueAt(bar, 4).toString();
        String f = tablestaff.getValueAt(bar, 5).toString();
        
        kode.setText(a);
        nama.setText(b);
        if("Laki-Laki".equals(c)){
            laki.setSelected(true);
        }else {
            perempuan.setSelected(true);
        }
        agama.setSelectedItem(d);
        alamat.setText(e);
        telp.setText(f);
    }//GEN-LAST:event_tablestaffMouseClicked

