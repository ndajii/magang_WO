    private void editActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_editActionPerformed
        // TODO add your handling code here:
        String jenis = null;
        if(laki.isSelected()){
            jenis = "Laki-Laki";
        }else{
            jenis = "Perempuan";
          }
        
        try{
            String sql = "update tb_karyawan set "
                    + "dbkodekar=?,"
                    + "dbnamakar=?,"
                    + "dbjeniskelkar=?,"
                    + "dbagamakar=?, "
                    + "dbalamatkar=?, "
                    + "dbtelpkar=?"
                    + "where dbkodekar='"+kode.getText()+"'";
            PreparedStatement stat = conn.prepareStatement(sql);
            stat.setString(1, kode.getText());
            stat.setString(2, nama.getText());
            stat.setString(3, jenis);
            stat.setString(4, agama.getSelectedItem().toString());
            stat.setString(5, alamat.getText());
            stat.setString(6, telp.getText());
            stat.executeUpdate();
            JOptionPane.showMessageDialog(null, "data berhasil diubah");
            kosong();
            }
        catch (SQLException e){
            JOptionPane.showMessageDialog(null, "data gagal diubah"+e);
            }
            aktif();
            tabelkaryawan();
    }//GEN-LAST:event_editActionPerformed

